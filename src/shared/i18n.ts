const DICTS: Record<Lang, Record<MessageKey, string>> = { pt, en }

export function t(lang: Lang, key: MessageKey): string {
  return DICTS[lang][key]
}

export const LANG_LABEL_KEYS: Record<LangChoice, MessageKey> = { auto: 'langAuto', pt: 'langPt', en: 'langEn' }

/** Fills every [data-i18n]/[data-i18n-placeholder]/[data-i18n-title] node under root. */
export function applyI18n(root: ParentNode, lang: Lang): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    el.textContent = t(lang, el.dataset['i18n'] as MessageKey)
  }
  for (const el of root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]')) {
    el.placeholder = t(lang, el.dataset['i18nPlaceholder'] as MessageKey)
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    el.title = t(lang, el.dataset['i18nTitle'] as MessageKey)
  }
}
